/// Справочник стран для онбординга («Откуда вы?»).
/// Флаг — эмодзи, вычисляется из ISO 3166-1 alpha-2 кода, вручную не хранится.
class Country {
  const Country({
    required this.code,
    required this.nameRu,
    required this.nameEn,
  });

  final String code;
  final String nameRu;
  final String nameEn;

  String get flag => String.fromCharCodes(
    code.toUpperCase().codeUnits.map((c) => 0x1F1E6 + (c - 0x41)),
  );
}

